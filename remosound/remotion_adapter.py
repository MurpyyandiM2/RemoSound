"""Export the local sound bank for a Remotion project.

Remotion serves static files through ``staticFile()``, which needs a path
relative to the project's ``public/`` directory and written with forward
slashes on every platform. :func:`export_registry` therefore records every
sound as ``remosound/<category>/<file>`` — the same layout
:func:`stage_into_remotion` copies into ``public/`` — and
:func:`export_typescript_helper` emits a dependency-free module so a scene can
look a sound up by id or search for one by text.
"""

from __future__ import annotations

import json
import os
import shutil
import tempfile
from pathlib import Path, PurePosixPath

from remosound.storage import StorageManager, category_slug

REGISTRY_VERSION = 1
REGISTRY_NAME = "sound-bank.json"
HELPER_NAME = "sound-bank.ts"

# Remotion-side directory that mirrors the bank layout inside public/.
REMOTION_PREFIX = "remosound"

_TS_HEADER = """\
// Generated by RemoSound. Do not edit by hand.
// Regenerate with `python run.py --rebuild-index` after changing the bank.
"""


def export_registry(entries: list[dict], output_path: Path) -> Path:
    """Write ``{"version": 1, "sounds": [...]}`` to ``output_path``.

    Each sound carries ``id, title, category, file, src`` where ``src`` is the
    Remotion-safe path ``remosound/<category>/<file>``. Sounds are written in
    id order so regenerating an unchanged bank produces an identical file.
    """

    output = Path(output_path)
    registry = {
        "version": REGISTRY_VERSION,
        "sounds": sorted((_registry_entry(entry) for entry in entries), key=lambda sound: str(sound["id"])),
    }

    output.parent.mkdir(parents=True, exist_ok=True)
    _write_atomic(output, json.dumps(registry, ensure_ascii=False, indent=2) + "\n")
    return output


def export_typescript_helper(registry_path: Path, output_path: Path) -> Path:
    """Write ``sound-bank.ts`` from the registry at ``registry_path``.

    The generated module has no imports: drop it into any Remotion project and
    it type-checks on its own.
    """

    source = Path(registry_path)
    registry = _load_registry(source)
    sounds = [
        {
            "id": sound.get("id"),
            "title": sound.get("title", ""),
            "category": sound.get("category", ""),
            "file": sound.get("file", ""),
            "src": sound.get("src", ""),
        }
        for sound in registry["sounds"]
    ]

    document = (
        _TS_HEADER
        + "\n"
        + _SOUND_ENTRY_TYPE
        + f"\nexport const SOUND_BANK: SoundEntry[] = {json.dumps(sounds, ensure_ascii=False, indent=2)};\n"
        + _LOOKUP_FUNCTIONS
    )

    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    _write_atomic(output, document)
    return output


def stage_into_remotion(registry_path: Path, sound_root: Path, remotion_public_dir: Path) -> Path:
    """Copy the bank into a Remotion ``public/`` directory.

    Audio lands in ``<public>/remosound/<category>/`` and the registry is
    written to ``<public>/sound-bank.json``. The registry is copied last so a
    failed transfer never leaves a registry pointing at files that are not
    there. Returns the staged registry path.
    """

    source_registry = Path(registry_path)
    registry = _load_registry(source_registry)
    bank_root = Path(sound_root).resolve()
    public_dir = Path(remotion_public_dir)

    for sound in registry["sounds"]:
        relative = _remotion_relative(sound, source_registry)
        audio = _inside(bank_root, relative, "sound source")
        destination = _inside(public_dir, PurePosixPath(REMOTION_PREFIX, relative).as_posix(), "public directory")
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(audio, destination)

    staged = public_dir / REGISTRY_NAME
    staged.parent.mkdir(parents=True, exist_ok=True)
    _copy_atomic(source_registry, staged)
    return staged


def _write_atomic(path: Path, text: str) -> None:
    """Write ``text`` to ``path`` via a temp file in the same directory.

    A reader (Remotion, an editor) sees either the previous file or the new
    one, never a half-written registry, and a failed write removes its temp
    file instead of leaving debris in the user's project.
    """

    descriptor, temp_name = tempfile.mkstemp(dir=path.parent, prefix=f"{path.name}.", suffix=".tmp")
    temp_path = Path(temp_name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.replace(temp_path, path)
    except BaseException:
        temp_path.unlink(missing_ok=True)
        raise


def _copy_atomic(source: Path, destination: Path) -> None:
    """Copy ``source`` over ``destination`` without exposing a partial file."""

    descriptor, temp_name = tempfile.mkstemp(
        dir=destination.parent, prefix=f"{destination.name}.", suffix=".tmp"
    )
    os.close(descriptor)
    temp_path = Path(temp_name)
    try:
        shutil.copy2(source, temp_path)
        os.replace(temp_path, destination)
    except BaseException:
        temp_path.unlink(missing_ok=True)
        raise


def _registry_entry(entry: dict) -> dict:
    """One registry record from a manifest entry."""

    file_name = _file_name(entry)
    category = str(entry.get("category") or "")
    return {
        "id": entry.get("id"),
        "title": str(entry.get("title") or ""),
        "category": category,
        "file": file_name,
        "src": f"{REMOTION_PREFIX}/{category_slug(category)}/{file_name}",
    }


def _load_registry(registry_path: Path) -> dict:
    """Read a registry file and refuse anything this adapter cannot consume.

    Both consumers reject malformed payloads here rather than failing later
    with an ``AttributeError``, and an unrecognized ``version`` is an error
    instead of being silently treated as version 1.
    """

    path = Path(registry_path)
    try:
        registry = json.loads(path.read_text(encoding="utf-8"))
    except ValueError as error:
        raise ValueError(f"registry {path} is not valid JSON: {error}") from error

    if not isinstance(registry, dict):
        raise ValueError(f"registry {path} must be a JSON object, got {type(registry).__name__}")

    version = registry.get("version")
    if type(version) is not int or version != REGISTRY_VERSION:
        raise ValueError(
            f"registry {path} has unsupported version {version!r}; this build reads version {REGISTRY_VERSION}"
        )

    if not isinstance(registry.get("sounds"), list):
        raise ValueError(f"registry {path} must contain a 'sounds' list")

    return registry


def _file_name(entry: dict) -> str:
    """The bank file's name, normalized off whatever separator the bank used."""

    path = str(entry.get("path") or "").replace("\\", "/")
    name = PurePosixPath(path).name
    if not name:
        raise ValueError(f"sound entry {entry.get('id')!r} has no file path to export")
    return name


def _remotion_relative(sound: dict, registry_path: Path) -> str:
    """Strip the ``remosound/`` prefix from a registry ``src``."""

    src = str(sound.get("src") or "").replace("\\", "/")
    prefix = f"{REMOTION_PREFIX}/"
    relative = src[len(prefix) :] if src.startswith(prefix) else ""
    if not relative:
        raise ValueError(f"registry {registry_path} has a sound without a '{prefix}' src: {src!r}")
    return relative


def _inside(base: Path, relative: str, label: str) -> Path:
    """Resolve ``relative`` under ``base``, refusing paths that escape it."""

    resolved_base = base.resolve()
    candidate = (resolved_base / relative).resolve()
    if candidate != resolved_base and resolved_base not in candidate.parents:
        raise ValueError(f"{label} path escapes {resolved_base}: {relative!r}")
    return candidate


_SOUND_ENTRY_TYPE = """\
export type SoundEntry = {
  id: string;
  title: string;
  category: string;
  file: string;
  src: string;
};
"""

_LOOKUP_FUNCTIONS = """
export function getSound(id: string): SoundEntry | undefined {
  return SOUND_BANK.find((sound) => sound.id === id);
}

export function findSounds(query: string): SoundEntry[] {
  const needle = query.trim().toLowerCase();
  if (!needle) {
    return [];
  }
  return SOUND_BANK.filter((sound) =>
    [sound.id, sound.title, sound.category, sound.file, sound.src].some((field) =>
      field.toLowerCase().includes(needle),
    ),
  );
}
"""


def registry_paths(out: Path) -> tuple[Path, Path]:
    """Registry and helper paths beside the bank root (``public/`` in a project)."""

    parent = Path(out).parent
    return parent / REGISTRY_NAME, parent / HELPER_NAME


def write_index(storage: "StorageManager", out: Path) -> None:
    """Write ``sound-bank.json`` and then ``sound-bank.ts`` beside the bank root ``out``."""

    registry, helper = registry_paths(out)
    _refuse_to_empty_the_registry(storage, registry)
    export_registry(storage.entries(), registry)
    export_typescript_helper(registry, helper)


def _refuse_to_empty_the_registry(storage: "StorageManager", registry: Path) -> None:
    """Raise when an empty manifest would replace a registry full of sounds.

    An empty bank is usually a lost or corrupt manifest, not an intentional
    reset. Overwriting ``sound-bank.json`` (and then copying it into a
    Remotion ``public/``) would destroy the only remaining index of audio the
    user still has on disk, so the CLI stops and points at the quarantine file.
    """

    if storage.entries() or not registry.exists():
        return
    try:
        existing = json.loads(registry.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        # An unreadable registry holds nothing worth preserving.
        return
    sounds = existing.get("sounds") if isinstance(existing, dict) else None
    if not isinstance(sounds, list) or not sounds:
        return

    raise ValueError(
        f"{registry} already lists {len(sounds)} sound(s) but the manifest is empty; "
        f"refusing to overwrite it. Check {storage.corrupt_manifest_path} "
        "and restore the bank before rebuilding."
    )
